  /// Find exact item by barcode
  FmcgItem? findByBarcode(String barcode) {
    final clean = barcode.trim();
    if (clean.isEmpty) return null;
    try {
      return catalog.firstWhere((item) => item.barcode == clean);
    } catch (_) {
      return null;
    }
  }

  /// Search catalog by query (matches barcode, english name, hindi name, brand, keywords)
  List<FmcgItem> search(String query, {int limit = 8}) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return [];

    final matches = catalog.where((item) {
      if (item.barcode.contains(clean)) return true;
      if (item.name.toLowerCase().contains(clean)) return true;
      if (item.nameHi.toLowerCase().contains(clean)) return true;
      if (item.brand.toLowerCase().contains(clean)) return true;
      if (item.packSize.toLowerCase().contains(clean)) return true;
      for (final kw in item.searchKeywords) {
        if (kw.toLowerCase().contains(clean)) return true;
      }
      return false;
    }).toList();

    // Priority sort: exact barcode first, then name startswith, then others
    matches.sort((a, b) {
      if (a.barcode == clean && b.barcode != clean) return -1;
      if (b.barcode == clean && a.barcode != clean) return 1;
      final aNameStarts = a.name.toLowerCase().startsWith(clean);
      final bNameStarts = b.name.toLowerCase().startsWith(clean);
      if (aNameStarts && !bNameStarts) return -1;
      if (!aNameStarts && bNameStarts) return 1;
      return 0;
    });

    return matches.take(limit).toList();
  }
