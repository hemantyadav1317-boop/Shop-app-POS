  static ProduceItem? findById(String id) {
    try {
      final clean = id.trim().toLowerCase();
      return allItems.firstWhere((item) =>
          item.id.toLowerCase() == clean ||
          (clean == 'tomato' && item.id == 'tamatar') ||
          (clean == 'cucumber' && item.id == 'kheera') ||
          (clean == 'potato' && item.id == 'aloo') ||
          (clean == 'onion' && item.id == 'pyaj') ||
          (clean == 'ginger' && item.id == 'adrak') ||
          (clean == 'garlic' && item.id == 'lahsun') ||
          (clean == 'pomegranate' && item.id == 'anaar') ||
          item.aliases.any((a) => a.toLowerCase() == clean));
    } catch (_) {
      return null;
    }
  }

  static ProduceItem? findByText(String query) {
    final clean = query.trim().toLowerCase();
    for (final item in allItems) {
      if (item.id.toLowerCase() == clean ||
          item.hindiName.toLowerCase() == clean ||
          item.englishName.toLowerCase() == clean) {
        return item;
      }
      for (final a in item.aliases) {
        if (clean.contains(a.toLowerCase()) || a.toLowerCase().contains(clean)) {
          return item;
        }
      }
    }
    return null;
  }
