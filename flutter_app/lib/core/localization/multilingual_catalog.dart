    if (lower.contains('ginger') || lower.contains('adrak') || lower.contains('अदरक')) return 'ginger';
    if (lower.contains('garlic') || lower.contains('lahsun') || lower.contains('लहसुन') || lower.contains('लसूण')) return 'garlic';
    if (lower.contains('chilli') || lower.contains('chili') || lower.contains('mirch') || lower.contains('मिर्च')) return 'chilli';
    if (lower.contains('coriander') || lower.contains('dhaniya') || lower.contains('धनिया')) return 'coriander';
    if (lower.contains('spinach') || lower.contains('palak') || lower.contains('पालक')) return 'spinach';
    if (lower.contains('okra') || lower.contains('ladyfinger') || lower.contains('bhindi') || lower.contains('भिंडी')) return 'okra';
    if (lower.contains('apple') || lower.contains('seb') || lower.contains('सेब')) return 'apple';
    if (lower.contains('banana') || lower.contains('kela') || lower.contains('केला')) return 'banana';
    if (lower.contains('mango') || lower.contains('aam') || lower.contains('आम')) return 'mango';
    if (lower.contains('orange') || lower.contains('santra') || lower.contains('संतरा')) return 'orange';
    if (lower.contains('watermelon') || lower.contains('tarbooj') || lower.contains('तरबूज')) return 'watermelon';
    if (lower.contains('papaya') || lower.contains('papita') || lower.contains('पपीता')) return 'papaya';
