  /// Looks up localized produce name for a given produce identifier or raw name.
  static String? lookup(String name, String localeCode, {String? nameEn, String? nameHi}) {
    // Try matching by raw name, nameEn, or nameHi
    final key = _matchKey(name) ?? (nameEn != null ? _matchKey(nameEn) : null) ?? (nameHi != null ? _matchKey(nameHi) : null);
    if (key == null) return null;

    final entry = produce[key];
    if (entry == null) return null;

    return entry[localeCode] ?? entry['hi'] ?? entry['en'];
  }
